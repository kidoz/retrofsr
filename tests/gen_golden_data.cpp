// Regenerates the on-disk golden images. Run after an intentional image-quality change:
//
//   just golden
//
// (equivalently: ./buildDir/retrofsr_golden_gen [tests/data/golden]), then review the
// image diffs before committing. Writes one PAM (or raw .bin for 565) file per case
// plus manifest.txt with the exact case metadata.

#include "golden_support.hpp"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>

namespace {

void write_file(const std::filesystem::path& path, const std::string& header, const std::vector<std::byte>& pixels) {
    std::ofstream out(path, std::ios::binary);
    out.write(header.data(), static_cast<std::streamsize>(header.size()));
    out.write(reinterpret_cast<const char*>(pixels.data()), static_cast<std::streamsize>(pixels.size()));
    if (!out) {
        throw std::runtime_error("cannot write golden file: " + path.string());
    }
}

} // namespace

int main(int argc, char** argv) {
    try {
        const std::filesystem::path out_dir = argc > 1 ? argv[1] : "tests/data/golden";
        std::filesystem::create_directories(out_dir);

        // Remove stale golden artifacts so matrix shrinks do not leave orphans behind.
        for (const auto& entry : std::filesystem::directory_iterator(out_dir)) {
            const auto ext = entry.path().extension();
            if (ext == ".pam" || ext == ".bin" || entry.path().filename() == "manifest.txt") {
                std::filesystem::remove(entry.path());
            }
        }

        std::ofstream manifest(out_dir / "manifest.txt");
        manifest << "# Generated by tests/gen_golden_data.cpp; regenerate with: just golden\n";
        manifest << "# name file filter color_space sharpen dither alpha dst_format source sharpening "
                    "src dst bytes\n";

        for (const auto& config : golden::configs) {
            const auto pixels = golden::render(config);
            const std::string file_name = golden_file_name(config);
            const std::string header = file_name.ends_with(".pam") ? golden::pam_header(config) : std::string{};
            write_file(out_dir / file_name, header, pixels);

            manifest << golden::case_name(config) << ' ' << file_name << ' ' << static_cast<int>(config.filter) << ' '
                     << static_cast<int>(config.color_space) << ' ' << static_cast<int>(config.sharpen) << ' '
                     << static_cast<int>(config.dither) << ' ' << static_cast<int>(config.alpha) << ' '
                     << static_cast<int>(config.dst_format) << ' ' << static_cast<int>(config.source) << ' '
                     << config.sharpening << ' ' << config.src_width << 'x' << config.src_height << ' '
                     << config.dst_width << 'x' << config.dst_height << ' ' << pixels.size() << '\n';
        }
        if (!manifest) {
            throw std::runtime_error("cannot write manifest");
        }

        std::printf("wrote %zu golden files to %s\n", golden::configs.size(), out_dir.string().c_str());
        return 0;
    } catch (const std::exception& e) {
        std::fprintf(stderr, "retrofsr_golden_gen: %s\n", e.what());
        return 1;
    }
}
