// Regenerates the golden-image expectations. Run after an intentional image-quality change:
//
//   meson compile -C buildDir retrofsr_golden_gen
//   ./buildDir/retrofsr_golden_gen > tests/golden_data.hpp
//
// (or `just golden`), then review the image diff before committing.

#include "golden_support.hpp"

#include <cstddef>
#include <cstdio>

int main() {
    const auto src = golden::make_source();

    std::printf("// Generated by tests/gen_golden_data.cpp; do not edit by hand.\n");
    std::printf("// Regenerate with: just golden\n");
    std::printf("#pragma once\n\n");
    std::printf("#include <array>\n#include <cstddef>\n#include <cstdint>\n\n");
    std::printf("// clang-format off\n");
    std::printf("namespace golden {\n\n");
    std::printf("inline constexpr std::array<std::array<std::uint8_t, %zu>, %zu> expected = {{\n", golden::dst_bytes,
                golden::configs.size());

    for (std::size_t case_index = 0; case_index < golden::configs.size(); ++case_index) {
        const auto& config = golden::configs[case_index];
        const auto out = golden::render(config, src);
        std::printf("    // case %zu: filter=%d color_space=%d sharpen=%d\n", case_index,
                    static_cast<int>(config.filter), static_cast<int>(config.color_space),
                    static_cast<int>(config.sharpen));
        std::printf("    {{");
        for (std::size_t i = 0; i < out.size(); ++i) {
            if (i % 20 == 0) {
                std::printf("\n        ");
            }
            std::printf("%u,", static_cast<unsigned>(static_cast<std::uint8_t>(out[i])));
        }
        std::printf("\n    }},\n");
    }

    std::printf("}};\n\n");
    std::printf("} // namespace golden\n");
    std::printf("// clang-format on\n");
    return 0;
}
